const IMPORT_LINE = 'import ToolCatalogCTA from "@/components/tools/ToolCatalogCTA";';

function addImport(src) {
  if (src.includes(IMPORT_LINE)) return src;
  const lines = src.split("\n");
  // find last top-level import line index
  let lastImport = -1;
  for (let i = 0; i < lines.length; i++) {
    if (/^import .*;?\s*$/.test(lines[i]) || /^import /.test(lines[i])) lastImport = i;
    // stop scanning once we hit non-import after imports block
    if (lastImport >= 0 && lines[i].trim() !== "" && !/^import /.test(lines[i]) && !lines[i].trim().startsWith("//")) {
      // allow multiline imports continuing; only break if line ends a statement region
    }
  }
  lines.splice(lastImport + 1, 0, IMPORT_LINE);
  return lines.join("\n");
}

function findAnchorLine(lines, anchor, kind) {
  for (let i = 0; i < lines.length; i++) {
    if (kind === "comment") {
      if (lines[i].includes(anchor)) return i;
    } else {
      if (lines[i].includes(anchor)) {
        // walk up to the opening of the enclosing block element (a line that opens a <div/<p/<section with no close on same line)
        let j = i;
        while (j > 0) {
          const t = lines[j].trim();
          if (/^<(div|p|section|aside|footer)\b/.test(t)) return j;
          j--;
        }
        return i;
      }
    }
  }
  return -1;
}

let report = [];
for (const [rel, anchor, kind] of targets) {
  if (!fs.existsSync(rel)) { report.push(`MISSING FILE: ${rel}`); continue; }
  let src = fs.readFileSync(rel, "utf8");
  if (src.includes("ToolCatalogCTA")) { report.push(`SKIP (already has rail): ${rel}`); continue; }
  const lines = src.split("\n");
  const idx = findAnchorLine(lines, anchor, kind);
  if (idx === -1) { report.push(`ANCHOR NOT FOUND: ${rel} :: ${anchor}`); continue; }
  const indent = (lines[idx].match(/^(\s*)/) || ["", ""])[1];
  const block = [
    `${indent}{/* Catalog rail */}`,
    `${indent}<ToolCatalogCTA className="py-2" />`,
    "",
  ];
  lines.splice(idx, 0, ...block);
  src = lines.join("\n");
  src = addImport(src);
  fs.writeFileSync(rel, src, "utf8");
  report.push(`OK: ${rel} (inserted before line ${idx + 1})`);
}
